# CPU/GPU 档位定义表 — 被 cpuctl 与 api.cgi 共用
# 格式: 键|名称|说明|little下限%|little上限%|medium下限%|medium上限%|big下限%|big上限%|GPU等级%
#
# 与原版(骁龙 SM8850)的差别: 原版写死的是 kHz 绝对值, 换机必错。
# 这里改成"占该簇可用天花板的百分比", 运行时由 cpuctl 探测出每簇真实天花板
# (2.0GHz / 2.8GHz / 3.2GHz) 再换算成具体频点, 并吸附到 scaling_available_frequencies
# 里真实存在的档位。百分比写错的后果只是"档位不理想", 不会写出不存在的频点。
#
# 百分比含义:
#   上限 0   = 锁该簇最低频
#   上限 100 = 放到该簇天花板(不一定是 cpuinfo_max, 本机被 mtk-cpufreq-hw 硬限)
#   下限 N   = 抬到天花板的 N%(保底频率, 防止降太狠)
# GPU等级%: 100 = 最高频(1612MHz), 0 = 最低频(338MHz), 线性映射到 49 档
# 写成 R 表示"按出厂快照还原", 不做写入

profiles_dump() {
    cat <<'EOF'
stock|出厂默认|系统原生调度，不做任何约束|0|100|0|100|0|100|R
floor|最低频率|全集群锁死最低频，只保证系统活着|0|0|0|0|0|0|0
