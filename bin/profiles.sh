saver|日常省电|刷视频看小说够用，日常使用几乎无感|0|46|0|38|0|30|22
balanced|日常均衡|默认推荐，性能与功耗的平衡点|0|64|0|56|0|46|42
boost|日常增强|应用启动更快，日常偏向性能|0|80|0|72|0|62|58
light|轻度游戏|王者/和平类，优先稳住帧率|12|92|10|86|8|76|72
heavy|重度游戏|原神/绝区零高画质，火力全开|22|100|18|97|15|92|88
max|全拉满测速|锁死天花板只跑分，5 分钟自动回落|100|100|100|100|100|100|100
EOF
}

profile_exists() {
    profiles_dump | grep -q "^$1|"
}
